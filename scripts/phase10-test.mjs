import assert from 'node:assert/strict';
import {DEFAULT_WISH} from '../src/data/themes.js';
import {MOTION_PRESETS,GIFT_SEALS,safeMotion,safeSeal,sealSymbol} from '../src/lib/motion.js';
import {encodeWish,decodeWish,sanitizeWish,makeShareUrl} from '../src/lib/share.js';
assert.equal(MOTION_PRESETS.length,3);
assert.equal(GIFT_SEALS.length,4);
assert.equal(safeMotion('unknown'),'cinematic');
assert.equal(safeSeal('bad'),'star');
assert.equal(sealSymbol('heart'),'♥');
const card={...DEFAULT_WISH,theme:'diwali',motion:'celebrate',seal:'flower',to:'ગુજરાતી ✨',from:'Manan',message:'Happy Diwali!'};
const decoded=decodeWish(encodeWish(card));
assert.equal(decoded.motion,'celebrate');
assert.equal(decoded.seal,'flower');
assert.equal(decoded.to,'ગુજરાતી ✨');
assert.equal(sanitizeWish({...card,motion:'evil',seal:'evil'}).motion,'cinematic');
assert.equal(sanitizeWish({...card,motion:'evil',seal:'evil'}).seal,'star');
const legacy={...DEFAULT_WISH};delete legacy.motion;delete legacy.seal;
assert.equal(decodeWish(encodeWish(legacy)).motion,'cinematic');
assert.equal(decodeWish(encodeWish(legacy)).seal,'star');
globalThis.window={location:{origin:'https://greetings.mananbhayani.online'}};
assert.ok(makeShareUrl(card).includes('#wish='));
console.log('PASS Phase 10: motion presets, personal seals, Unicode links, backward compatibility and sanitization');
